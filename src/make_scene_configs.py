#!/usr/bin/env python3
"""
Write configs/T1_<scene>.yaml for each multi-scene scene from the frozen
protocol (configs/protocol_v1.yaml). Nothing is chosen here:

  - feature constants, knn_k, label multiplier, needle band: copied from the protocol
  - training size: configs/train_image_sizes.yaml (pixel size of the images
    cfg_args names; cameras.json holds the COLMAP size, see protocol `changes`)
  - eval split: read from the model's cfg_args (eval=True -> every 8th held out)

Truck keeps its existing hand-written configs/T1_truck.yaml (same values;
asserted below).

Usage:
    python src/make_scene_configs.py
"""

import json
import re
import yaml

PROTOCOL = "configs/protocol_v1.yaml"
PATHS = {
    "bicycle":  "data/m360/bicycle/sparse/0",
    "garden":   "data/m360/garden/sparse/0",
    "room":     "data/m360/room/sparse/0",
    "playroom": "data/db/playroom/sparse/0",
}


def main():
    P = yaml.safe_load(open(PROTOCOL))
    f, lab, nd = P["features"], P["label"], P["needles_T5"]

    truck = yaml.safe_load(open("configs/T1_truck.yaml"))
    assert truck["knn_k"] == f["knn_k"]
    assert truck["unsupported_spacing_mult"] == lab["unsupported_spacing_mult"]
    assert truck["max_views"] == P["inputs"]["max_views"]
    for k, v in f["projection"].items():
        assert truck["projection"][k] == v, k
    print("truck config consistent with protocol: yes")

    sizes = yaml.safe_load(open("configs/train_image_sizes.yaml"))
    for scene, colmap in PATHS.items():
        mdir = f"data/models/{scene}"
        cj = json.load(open(f"{mdir}/cameras.json"))
        widths = sorted({c["width"] for c in cj})
        heights = sorted({c["height"] for c in cj})
        assert len(widths) == 1, f"{scene}: several cameras.json widths {widths}"
        args = open(f"{mdir}/cfg_args").read()
        ev = re.search(r"eval=(True|False)", args).group(1) == "True"
        images = re.search(r"images='([^']*)'", args).group(1)
        res = re.search(r"resolution=(-?\d+)", args).group(1)
        sz = sizes[scene]
        assert sz["images"] == images, f"{scene}: size file is for {sz['images']}, cfg_args says {images}"
        assert res == "1", f"{scene}: resolution={res} would rescale the images"
        assert sz["width"] <= 1600, "3DGS would downscale images wider than 1600 px"

        cfg = {
            "scene": scene,
            "protocol": PROTOCOL,
            "ply": f"{mdir}/point_cloud/iteration_30000/point_cloud.ply",
            "colmap": colmap,
            "out": f"out/features/{scene}.parquet",
            "max_views": P["inputs"]["max_views"],
            "knn_k": f["knn_k"],
            "unsupported_spacing_mult": lab["unsupported_spacing_mult"],
            "projection": dict(f["projection"], train_max_width=sz["width"],
                               train_height=sz["height"]),
            "eval_holdout": P["inputs"]["eval_holdout"] if ev else 0,
            "needle": {"top_pct": nd["top_pct"], "band_lo_pct": nd["band_lo_pct"],
                       "band_hi_pct": nd["band_hi_pct"]},
            "model_cameras_json": {"n": len(cj), "width": widths[0], "height": heights},
            "model_cfg_args": {"eval": ev, "images": images, "resolution": int(res)},
        }
        path = f"configs/T1_{scene}.yaml"
        with open(path, "w") as fh:
            fh.write(f"# T1 feature extraction — {scene}. GENERATED by src/make_scene_configs.py\n"
                     f"# from {PROTOCOL}; do not edit by hand.\n")
            yaml.safe_dump(cfg, fh, sort_keys=False)
        print(f"{path}: train {sz['width']}x{sz['height']} (cameras.json {widths[0]}x{heights}), eval={ev}, "
              f"images='{images}', resolution={res}, cameras.json n={len(cj)}")


if __name__ == "__main__":
    main()
